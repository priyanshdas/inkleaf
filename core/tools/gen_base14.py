"""Regenerates src/base14.rs from the Adobe AFM metrics bundled with reportlab.

PDFs are allowed to use the 14 standard fonts without embedding them or
listing glyph widths, so the redactor needs its own copy of those widths.
Run from the core/ directory:  python3 tools/gen_base14.py
"""
from pathlib import Path
from reportlab.pdfbase import _fontdata as fd

# Oblique faces share widths with their upright twins; Courier is all 600.
TABLES = {
    "HELVETICA": "Helvetica",
    "HELVETICA_BOLD": "Helvetica-Bold",
    "TIMES_ROMAN": "Times-Roman",
    "TIMES_BOLD": "Times-Bold",
    "TIMES_ITALIC": "Times-Italic",
    "TIMES_BOLD_ITALIC": "Times-BoldItalic",
    "SYMBOL": "Symbol",
    "ZAPF_DINGBATS": "ZapfDingbats",
}
ENCODINGS = {
    "WIN_ANSI": "WinAnsiEncoding",
    "STANDARD": "StandardEncoding",
    "MAC_ROMAN": "MacRomanEncoding",
    "SYMBOL_ENC": "SymbolEncoding",
    "ZAPF_ENC": "ZapfDingbatsEncoding",
}

lines = [
    "// Generated by tools/gen_base14.py from Adobe's AFM metrics. Don't edit by hand.",
    "",
]
for const, enc in ENCODINGS.items():
    names = ['"%s"' % (g or "") for g in fd.encodings[enc]]
    lines.append(f"pub static {const}: [&str; 256] = [")
    for i in range(0, 256, 8):
        lines.append("    " + ", ".join(names[i:i + 8]) + ",")
    lines.append("];")
    lines.append("")

for const, font in TABLES.items():
    pairs = sorted(fd.widthsByFontGlyph[font].items())
    lines.append(f"pub static {const}: &[(&str, u16)] = &[")
    for i in range(0, len(pairs), 6):
        chunk = pairs[i:i + 6]
        lines.append("    " + " ".join(f'("{g}", {w}),' for g, w in chunk))
    lines.append("];")
    lines.append("")

Path("src/base14.rs").write_text("\n".join(lines))
print("wrote src/base14.rs")
