// Writes build/installer-ai.nsh: the built-in AI models the Windows installer
// can download, with their sizes, links and SHA-256 checksums. They're read
// straight from the app's own list (src/shared/local-models.ts) and llama.cpp
// release (src/main/local-ai.ts), so the installer and the app can never
// disagree about what a model is. build/before-pack.cjs runs this before
// every Windows build, and the smoke tests check the file is up to date.
//
//   node scripts/installer-ai.mjs           write it
//   node scripts/installer-ai.mjs --check   fail if it's out of date

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(root, 'build', 'installer-ai.nsh');

/** "1.3 GB" or "32 MB", the way the app's AI settings show sizes. */
function size(bytes) {
  return bytes >= 1e9 ? `${(bytes / 1e9).toFixed(1)} GB` : `${Math.round(bytes / 1e6)} MB`;
}

function field(block, name) {
  const m = block.match(new RegExp(`\\b${name}:\\s*(?:msg\\()?(?:'([^']*)'|\`([^\`]*)\`|([\\d_.e]+))`));
  if (!m) throw new Error(`no ${name} in ${block.slice(0, 60)}…`);
  return m[1] ?? m[2] ?? m[3].replace(/_/g, '');
}

/** Text for an NSIS string in double quotes. */
const nsis = (text) => text.replace(/\$/g, '$$$$').replace(/"/g, '$\\"');

export function installerAi() {
  const source = fs.readFileSync(path.join(root, 'src', 'shared', 'local-models.ts'), 'utf8');
  const hf = source.match(/const HF = '([^']+)'/)[1];
  const fallback = source.match(/DEFAULT_LOCAL_MODEL = '([^']+)'/)[1];
  const list = source.slice(source.indexOf('export const LOCAL_MODELS'));
  const models = [...list.matchAll(/\{\s*id: '[^']+'[\s\S]*?phone:/g)].map(([b]) => ({
    id: field(b, 'id'),
    name: field(b, 'name'),
    blurb: field(b, 'blurb'),
    params: field(b, 'params'),
    memory: Number(field(b, 'memory')),
    file: field(b, 'file'),
    url: field(b, 'url').replace('${HF}', hf),
    sha256: field(b, 'sha256'),
    size: Number(field(b, 'size')),
  }));
  if (models.length < 1) throw new Error('found no models in local-models.ts');

  const ai = fs.readFileSync(path.join(root, 'src', 'main', 'local-ai.ts'), 'utf8');
  const tag = ai.match(/const LLAMA_TAG = '([^']+)'/)[1];
  const win = ai.match(/'win32-x64':\s*(\{[^}]+\})/)[1];
  const runtime = { file: field(win, 'file'), sha256: field(win, 'sha256'), size: Number(field(win, 'size')) };

  const lines = [
    '; Generated by scripts/installer-ai.mjs from src/shared/local-models.ts and',
    '; src/main/local-ai.ts. Change those, not this file.',
    '',
    `!define AI_ENGINE_DIR "llama-${tag}"`,
    `!define AI_ENGINE_FILE "${runtime.file}"`,
    `!define AI_ENGINE_URL "https://github.com/ggml-org/llama.cpp/releases/download/${tag}/${runtime.file}"`,
    `!define AI_ENGINE_SHA256 "${runtime.sha256}"`,
    `!define AI_ENGINE_SIZE "${size(runtime.size)}"`,
    `!define AI_ENGINE_MB ${Math.round(runtime.size / 1e6)}`,
    '',
    `!define AI_COUNT ${models.length}`,
    `!define AI_DEFAULT ${models.findIndex((m) => m.id === fallback) + 1}`,
    '',
  ];
  models.forEach((m, i) => {
    const n = i + 1;
    lines.push(
      `; ${m.id}${m.id === fallback ? ' (the app picks this one to begin with)' : ''}`,
      `!define AI_${n}_NAME "${nsis(m.name)}"`,
      `!define AI_${n}_BLURB "${nsis(m.blurb)}"`,
      `!define AI_${n}_PARAMS "${m.params}"`,
      `!define AI_${n}_MEMORY "${Math.round(m.memory / 1e9)} GB"`,
      `!define AI_${n}_MODEL "${m.file.replace(/-Q\d.*$/, '')}"`,
      `!define AI_${n}_FILE "${m.file}"`,
      `!define AI_${n}_URL "${m.url}"`,
      `!define AI_${n}_SHA256 "${m.sha256}"`,
      `!define AI_${n}_SIZE "${size(m.size)}"`,
      `!define AI_${n}_MB ${Math.round(m.size / 1e6)}`,
      '',
    );
  });
  // NSIS can't loop over a list as it builds, so this does it: inserts
  // MACRO once for each model, with the model's number
  lines.push('!macro inkleafEachModel MACRO');
  models.forEach((_, i) => lines.push(`  !insertmacro \${MACRO} ${i + 1}`));
  lines.push('!macroend', '');
  return lines.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = installerAi();
  if (process.argv.includes('--check')) {
    // a Windows checkout may have turned the line endings into CRLF
    const now = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
    if (now !== text) {
      console.error('build/installer-ai.nsh is out of date: run node scripts/installer-ai.mjs');
      process.exit(1);
    }
  } else {
    fs.writeFileSync(target, text);
    console.log(`Wrote ${path.relative(root, target)}`);
  }
}
