function writeIcons() {
  const lines = [
    '// Generated by scripts/build.mjs from lucide-static (ISC licence).',
    '// Add names to the list in that script rather than editing this file.',
    '',
    'export const icons: Record<string, string> = {',
  ];
  for (const name of iconNames) {
    const raw = fs.readFileSync(nm('lucide-static', 'icons', `${name}.svg`), 'utf8');
    const svg = raw
      .replace(/<!--.*?-->/gs, '')
      .replace(/\s*class="[^"]*"/, '')
      .replace(/\s*width="24"\s*height="24"/, '')
      .replace(/\s+/g, ' ')
      .replace(/> </g, '><')
      .replace(/ >/g, '>')
      .trim();
    lines.push(`  '${name}': '${svg.replace(/'/g, "\\'")}',`);
  }
  lines.push('};', '');
  const target = r('src', 'renderer', 'generated', 'icons.ts');
  const next = lines.join('\n');
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== next) {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, next);
  }
}

// --- terms and privacy ------------------------------------------------------
// TERMS.md and PRIVACY.md are the single source. The app shows them from
// Help, and the installers show them (as plain text) before installing.

function plainText(markdown) {
  return markdown
    .replace(/^#+\s*/gm, '')
    .replace(/\*\*(.+?)\*\*/g, '$1')
    .replace(/\[([^\]]+)\]\(([^)]+)\)/g, '$1 ($2)')
    .replace(/^\| --- .*\n/gm, '')
    .replace(/^\| (.*) \|$/gm, (_, row) => row.split(' | ').join(' - '))
    .replace(/[“”]/g, '"').replace(/[‘’]/g, "'").replace(/—/g, '-');
}

function writeLegal() {
  const terms = fs.readFileSync(r('TERMS.md'), 'utf8');
  const privacy = fs.readFileSync(r('PRIVACY.md'), 'utf8');
  const legal = path.join(out, 'renderer', 'legal');
  fs.mkdirSync(legal, { recursive: true });
  fs.writeFileSync(path.join(legal, 'terms.md'), terms);
  fs.writeFileSync(path.join(legal, 'privacy.md'), privacy);
  const text = [
    'Please read these terms and the privacy policy. By installing Inkleaf you agree to them.',
    '',
    plainText(terms),
    '',
    '========================================================================',
    '',
    plainText(privacy),
    '',
    '========================================================================',
    '',
    'Inkleaf is free software under the GNU General Public License, version 3 or later.',
    'The full licence is installed with the app (LICENSE.txt) and is at https://www.gnu.org/licenses/gpl-3.0.html',
    '',
  ].join('\r\n').replace(/\r?\n/g, '\r\n');
  // a byte-order mark tells the Windows installer the file is UTF-8
  for (const name of ['installer-terms.txt', 'license_en.txt']) {
    fs.writeFileSync(r('build', name), '\ufeff' + text);
  }
}

// --- static files ----------------------------------------------------------

function copyStatic() {
  const renderer = path.join(out, 'renderer');
  copy(r('src', 'renderer', 'index.html'), path.join(renderer, 'index.html'));
  copy(r('src', 'renderer', 'styles.css'), path.join(renderer, 'styles.css'));
  copy(r('src', 'renderer', 'assets'), path.join(renderer, 'assets'));
  // interface translations (strings.json is only the English list, for translators)
  const i18n = r('src', 'renderer', 'i18n');
  if (fs.existsSync(i18n)) {
    for (const f of fs.readdirSync(i18n).filter((f) => f.endsWith('.json') && f !== 'strings.json')) {
      copy(path.join(i18n, f), path.join(renderer, 'i18n', f));
    }
  }
  const font = nm('@fontsource-variable', 'instrument-sans', 'files');
  for (const subset of ['latin', 'latin-ext']) {
    for (const style of ['normal', 'italic']) {
      copy(path.join(font, `instrument-sans-${subset}-standard-${style}.woff2`),
        path.join(renderer, 'assets', 'fonts', `instrument-sans-${subset}-${style}.woff2`));
    }
  }
  copy(prebuiltWasm, path.join(renderer, 'core.wasm'));

  // Noto fonts for every script except Chinese, Japanese and Korean (those
  // are large and download on first use): about 200 KB a style each.
  const noto = path.join(renderer, 'assets', 'fonts', 'noto');
  for (const pkg of NOTO_PACKAGES) {
    const dir = nm('@expo-google-fonts', pkg);
    const base = fs.readdirSync(path.join(dir, '400Regular')).find((f) => f.endsWith('.ttf')).replace(/_400Regular\.ttf$/, '');
    const styles = { '400Regular': 'Regular', '700Bold': 'Bold', '400Regular_Italic': 'Italic', '700Bold_Italic': 'BoldItalic' };
    for (const [weight, style] of Object.entries(styles)) {
      const from = path.join(dir, weight, `${base}_${weight}.ttf`);
      if (fs.existsSync(from)) copy(from, path.join(noto, `${base}-${style}.ttf`));
    }
  }
  copy(nm('@expo-google-fonts', 'noto-sans', 'LICENSE_FONT'), path.join(noto, 'OFL.txt'));

  const pdfjs = path.join(renderer, 'vendor', 'pdfjs');
  copy(nm('pdfjs-dist', 'build', 'pdf.worker.min.mjs'), path.join(pdfjs, 'pdf.worker.mjs'));
  for (const dir of ['cmaps', 'standard_fonts', 'wasm', 'iccs']) {
    copy(nm('pdfjs-dist', dir), path.join(pdfjs, dir));
  }
  copy(nm('pdfjs-dist', 'LICENSE'), path.join(pdfjs, 'LICENSE'));

  // OCR runs fully offline: the engine, its worker and the language models
  // all ship with the app. Only the LSTM builds are needed (that's the
  // recognition mode we use), with and without SIMD for older CPUs.
  const ocr = path.join(renderer, 'vendor', 'tesseract');
  copy(nm('tesseract.js', 'dist', 'worker.min.js'), path.join(ocr, 'worker.min.js'));
  for (const core of ['tesseract-core-lstm.wasm.js', 'tesseract-core-simd-lstm.wasm.js', 'tesseract-core-relaxedsimd-lstm.wasm.js']) {
    copy(nm('tesseract.js-core', core), path.join(ocr, 'core', core));
  }
  for (const lang of OCR_LANGUAGES) {
    copy(nm('@tesseract.js-data', lang, '4.0.0_best_int', `${lang}.traineddata.gz`), path.join(ocr, 'lang', `${lang}.traineddata.gz`));
  }
  copy(nm('tesseract.js', 'LICENSE.md'), path.join(ocr, 'LICENSE.md'));

  // HarfBuzz's font subsetter, for writing fonts into PDFs
  copy(nm('harfbuzzjs', 'dist', 'harfbuzz-subset.wasm'), path.join(renderer, 'vendor', 'harfbuzz', 'harfbuzz-subset.wasm'));
  copy(nm('harfbuzzjs', 'LICENSE'), path.join(renderer, 'vendor', 'harfbuzz', 'LICENSE'));
}

