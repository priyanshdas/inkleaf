// --- TypeScript ------------------------------------------------------------

const common = {
  bundle: true,
  sourcemap: watch ? 'inline' : false,
  // INKLEAF_PROFILE=1 keeps names readable for CPU profiles
  minify: !watch && !process.env.INKLEAF_PROFILE,
  legalComments: 'linked',
  logLevel: 'info',
  target: 'es2023',
};

const targets = [
  {
    ...common,
    entryPoints: [r('src', 'main', 'main.ts')],
    outfile: path.join(out, 'main.js'),
    platform: 'node',
    format: 'cjs',
    // the updater ships as a normal dependency and is loaded from node_modules
    external: ['electron', 'electron-updater'],
  },
  {
    ...common,
    entryPoints: [r('src', 'main', 'preload.ts')],
    outfile: path.join(out, 'preload.js'),
    platform: 'node',
    format: 'cjs',
    external: ['electron'],
  },
  {
    ...common,
    entryPoints: [r('src', 'renderer', 'app.ts')],
    outdir: path.join(out, 'renderer'),
    // the PDF writer and its fonts become separate files, loaded on first use
    splitting: true,
    chunkNames: 'chunks/[name]-[hash]',
    platform: 'browser',
    format: 'esm',
  },
  {
    ...common,
    entryPoints: [r('src', 'renderer', 'core-worker.ts')],
    outfile: path.join(out, 'renderer', 'core-worker.js'),
    platform: 'browser',
    format: 'esm',
  },
];

fs.rmSync(out, { recursive: true, force: true });
writeIcons();
copyStatic();
writeLegal();

if (watch) {
  for (const options of targets) {
    const ctx = await context(options);
    await ctx.watch();
  }
  fs.watch(r('src', 'renderer'), (_, file) => {
    if (file === 'index.html' || file === 'styles.css') copyStatic();
  });
  console.log('watching for changes…');
} else {
  await Promise.all(targets.map((options) => build(options)));
}
