// Builds everything Electron needs into ./app
//
//   node scripts/build.mjs          one-off build
//   node scripts/build.mjs --watch  rebuild TypeScript on change
//   node scripts/build.mjs --core   also recompile the Rust core (needs cargo)

import { build, context } from 'esbuild';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'app');
const args = new Set(process.argv.slice(2));
const watch = args.has('--watch');

const r = (...p) => path.join(root, ...p);
const nm = (...p) => r('node_modules', ...p);

function copy(from, to) {
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.cpSync(from, to, { recursive: true });
}

// --- Rust core -------------------------------------------------------------

const prebuiltWasm = r('core', 'prebuilt', 'inkleaf_core.wasm');

if (args.has('--core')) {
  console.log('compiling Rust core to WebAssembly…');
  execFileSync('cargo', ['build', '--release', '--target', 'wasm32-unknown-unknown'], {
    cwd: r('core'),
    stdio: 'inherit',
  });
  copy(r('core', 'target', 'wasm32-unknown-unknown', 'release', 'inkleaf_core.wasm'), prebuiltWasm);
}

if (!fs.existsSync(prebuiltWasm)) {
  console.error('core/prebuilt/inkleaf_core.wasm is missing. Run `npm run build:core` (needs Rust).');
  process.exit(1);
}

